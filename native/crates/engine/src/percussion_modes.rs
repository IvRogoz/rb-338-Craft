pub(super) fn shape(kit: usize, id: usize, variant: bool, control: f32) -> Option<&'static Sound> {
    if id == 2 {
        let raw = (((control + 6.) / 12. * 127.).round() as usize).min(127);
        return Some(&SOUNDS[8 + kit * 5 + ((raw * 5) >> 7)]);
    }
    let index = match (kit, id, variant) {
        (1, 3, _) => 0,
        (1, 4, _) => 1,
        (1, 5, _) => 2,
        (1, 6, _) => 3,
        (0, 3, false) => 4,
        (0, 4, false) => 5,
        (0, 5, false) => 6,
        (0, 6, false) => 7,
        (0, 3, true) => 18,
        (0, 4, true) => 19,
        (0, 5, true) => 20,
        (0, 6, true) => 21,
        _ => return None,
    };
    Some(&SOUNDS[index])
}
